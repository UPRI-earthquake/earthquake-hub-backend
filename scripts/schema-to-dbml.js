// Prints the PostgreSQL schema as DBML (https://dbml.dbdiagram.io), read from the database the PG_*
// settings name: enums, then each table (columns with types, keys, defaults and comments; indexes; check
// rules in its note), then every foreign key with its ON DELETE rule. docs/postgres-schema.dbml is its
// output after the latest migration: regenerate it whenever a migration changes the schema, and paste it
// into https://dbdiagram.io to see the diagram (DB_SCHEMA.md).
//
//   npm run db:pg:migrate && npm run db:pg:dbml > docs/postgres-schema.dbml
try { require('dotenv/config'); } catch (_) { /* prod images don't ship dotenv */ }
const { db } = require('../src/db/knex');

// Knex's own bookkeeping and PostGIS's reference table aren't part of the app's schema
const SKIPPED_TABLES = new Set(['knex_migrations', 'knex_migrations_lock', 'spatial_ref_sys']);
const ON_DELETE = { a: 'no action', r: 'restrict', c: 'cascade', n: 'set null', d: 'set default' };

const quoteName = (name) => (/^[a-z_][a-z0-9_]*$/.test(name) ? name : `"${name}"`);
const quoteType = (type) => (/^[a-z_][a-z0-9_]*$/.test(type) ? type : `"${type}"`);
const text = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

async function readSchema() {
  const rows = async (sql) => (await db.raw(sql)).rows;
  const enums = await rows(`
    SELECT t.typname AS name, array_agg(e.enumlabel::text ORDER BY e.enumsortorder) AS labels
    FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public' GROUP BY t.typname ORDER BY t.typname`);
  const tables = (await rows(`
    SELECT c.oid, c.relname AS name, obj_description(c.oid, 'pg_class') AS comment
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.oid`)).filter((t) => !SKIPPED_TABLES.has(t.name));
  const columns = await rows(`
    SELECT a.attrelid AS table_oid, a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type,
      a.attnotnull AS not_null, a.attgenerated AS generated, pg_get_expr(d.adbin, d.adrelid) AS expression,
      col_description(a.attrelid, a.attnum) AS comment
    FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE a.attnum > 0 AND NOT a.attisdropped AND a.attrelid IN (${tables.map((t) => t.oid).join(',') || 0})
    ORDER BY a.attrelid, a.attnum`);
  const constraints = await rows(`
    SELECT con.conrelid AS table_oid, con.conname AS name, con.contype AS type, con.confdeltype AS on_delete,
      con.conindid AS index_oid, pg_get_constraintdef(con.oid) AS definition,
      (SELECT array_agg(a.attname::text ORDER BY k.ord) FROM unnest(con.conkey) WITH ORDINALITY k(num, ord)
         JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.num) AS columns,
      ref.relname AS ref_table,
      (SELECT array_agg(a.attname::text ORDER BY k.ord) FROM unnest(con.confkey) WITH ORDINALITY k(num, ord)
         JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.num) AS ref_columns
    FROM pg_constraint con LEFT JOIN pg_class ref ON ref.oid = con.confrelid
    WHERE con.conrelid IN (${tables.map((t) => t.oid).join(',') || 0})
    ORDER BY con.conrelid, con.conname`);
  const indexes = await rows(`
    SELECT i.indrelid AS table_oid, i.indexrelid AS index_oid, ic.relname AS name, i.indisunique AS is_unique,
      am.amname AS method, pg_get_expr(i.indpred, i.indrelid) AS predicate,
      (SELECT array_agg(pg_get_indexdef(i.indexrelid, k.ord::int, true) ORDER BY k.ord)
         FROM generate_series(1, i.indnkeyatts) k(ord)) AS keys
    FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid JOIN pg_am am ON am.oid = ic.relam
    WHERE i.indrelid IN (${tables.map((t) => t.oid).join(',') || 0})
    ORDER BY i.indrelid, ic.relname`);
  return { enums, tables, columns, constraints, indexes };
}

function toDbml({ enums, tables, columns, constraints, indexes }) {
  const out = [
    '// Earthquake Hub: the PostgreSQL schema, as the migrations (src/db/migrations) build it.',
    '// Generated by scripts/schema-to-dbml.js: regenerate it after a migration, don\'t edit it by hand.',
    '// Paste into https://dbdiagram.io to see the diagram. Docs: DB_SCHEMA.md',
    '',
    'Project earthquake_hub {',
    "  database_type: 'PostgreSQL'",
    '}',
    '',
  ];

  enums.forEach((e) => {
    out.push(`Enum ${quoteName(e.name)} {`, ...e.labels.map((label) => `  ${quoteName(label)}`), '}', '');
  });

  tables.forEach((table) => {
    const own = (list) => list.filter((row) => row.table_oid === table.oid);
    const tableConstraints = own(constraints);
    const primary = tableConstraints.find((c) => c.type === 'p');
    const singleUnique = new Set(tableConstraints.filter((c) => c.type === 'u' && c.columns.length === 1).map((c) => c.columns[0]));
    const constraintIndexes = new Set(tableConstraints.filter((c) => ['p', 'u'].includes(c.type)).map((c) => c.index_oid));

    out.push(`Table ${quoteName(table.name)} {`);
    own(columns).forEach((column) => {
      const settings = [];
      if (primary && primary.columns.length === 1 && primary.columns[0] === column.name) settings.push('pk');
      else if (column.not_null) settings.push('not null');
      if (singleUnique.has(column.name)) settings.push('unique');
      if (column.expression && !column.generated) settings.push(`default: \`${column.expression}\``);
      const notes = [column.generated ? `generated: ${column.expression}` : null, column.comment].filter(Boolean);
      if (notes.length > 0) settings.push(`note: ${text(notes.join('. '))}`);
      out.push(`  ${quoteName(column.name)} ${quoteType(column.type)}${settings.length ? ` [${settings.join(', ')}]` : ''}`);
    });

    const indexLines = [];
    if (primary && primary.columns.length > 1) indexLines.push(`(${primary.columns.map(quoteName).join(', ')}) [pk]`);
    tableConstraints.filter((c) => c.type === 'u' && c.columns.length > 1)
      .forEach((c) => indexLines.push(`(${c.columns.map(quoteName).join(', ')}) [unique, name: ${text(c.name)}]`));
    own(indexes).filter((index) => !constraintIndexes.has(index.index_oid)).forEach((index) => {
      const keys = index.keys.map((key) => (/^[a-z_][a-z0-9_]*$/.test(key) ? key : `\`${key}\``));
      const settings = [`name: ${text(index.name)}`];
      if (index.is_unique) settings.unshift('unique');
      if (index.method === 'btree' || index.method === 'hash') settings.push(`type: ${index.method}`);
      const notes = [index.method !== 'btree' && index.method !== 'hash' ? `${index.method} index` : null, index.predicate ? `where ${index.predicate}` : null].filter(Boolean);
      if (notes.length > 0) settings.push(`note: ${text(notes.join(', '))}`);
      indexLines.push(`${keys.length === 1 ? keys[0] : `(${keys.join(', ')})`} [${settings.join(', ')}]`);
    });
    if (indexLines.length > 0) out.push('', '  indexes {', ...indexLines.map((line) => `    ${line}`), '  }');

    const checks = tableConstraints.filter((c) => c.type === 'c').map((c) => `${c.name}: ${c.definition}`);
    const tableNotes = [table.comment, ...(checks.length ? ['Checks:', ...checks] : [])].filter(Boolean);
    // A multi-line note: DBML's ''' string, which takes quotes and backslashes as they are
    if (tableNotes.length > 0) out.push('', "  Note: '''", ...tableNotes.map((line) => `    ${line.replace(/'''/g, "' ' '")}`), "  '''");
    out.push('}', '');
  });

  constraints.filter((c) => c.type === 'f').forEach((c) => {
    const table = tables.find((t) => t.oid === c.table_oid).name;
    const from = c.columns.length === 1 ? `${quoteName(table)}.${quoteName(c.columns[0])}` : `${quoteName(table)}.(${c.columns.map(quoteName).join(', ')})`;
    const to = c.ref_columns.length === 1 ? `${quoteName(c.ref_table)}.${quoteName(c.ref_columns[0])}` : `${quoteName(c.ref_table)}.(${c.ref_columns.map(quoteName).join(', ')})`;
    out.push(`Ref ${quoteName(c.name)}: ${from} > ${to} [delete: ${ON_DELETE[c.on_delete] || 'no action'}]`);
  });
  return `${out.join('\n')}\n`;
}

readSchema()
  .then((schema) => process.stdout.write(toDbml(schema)))
  .catch((err) => {
    console.error(`schema-to-dbml failed: ${err.message}`);
    process.exitCode = 1;
  })
  .finally(() => db.destroy());
